"""Conservative candidate hold, not an agriculture or medical classifier.

All requests fail closed before generation. Exposure detection only selects the
more urgent copy; a missed wording never enables an advisory answer. This is an
English-language safeguard, not a multilingual emergency service.
"""
import re

POISON_SOURCE = 'https://www.poison.org/first-aid-for-poisonings'
NHS_SOURCE = 'https://www.nhs.uk/conditions/poisoning/'
EMERGENCY = (
    'Possible poisoning or chemical exposure needs urgent medical help. Contact '
    'your local poison centre or emergency medical service now. Do not make '
    'yourself or anyone else vomit. Do not wait for this app or for farm details. '
    'If the person has trouble breathing, collapses, has a seizure or cannot be '
    'awakened, call the local emergency number immediately. Follow the poison '
    'specialist or emergency clinician, not advice generated by this app.\n\n'
    'Safety guidance: ' + POISON_SOURCE + ' and ' + NHS_SOURCE + '\n\n'
    'This candidate safety message is in English. Multilingual medical or agricultural support has not been qualified.'
)
HOLD = (
    'Agriculture Chat is a candidate under safety review. Generated advice and '
    'source previews are paused, including general educational answers. No '
    'fertilizer, lime, pesticide, placement, timing or other field prescription '
    'is provided.\n\n'
    'A qualified local agronomist or agricultural extension service needs your '
    'country and locality, crop and growth stage, recent soil-test results '
    'including laboratory units and methods, field area and units, previous '
    'crops and fertilizer or manure use, irrigation and local conditions. '
    'These details do not unlock automatic prescriptions in this candidate. '
    'General or regional guidance cannot establish a recommendation for your field.\n\n'
    'If anyone may have swallowed, breathed in or otherwise been exposed to a '
    'harmful chemical, contact the local poison centre or emergency medical '
    'service now. Do not induce vomiting. Do not wait to collect farm details.\n'
    'Safety guidance: ' + POISON_SOURCE + ' and ' + NHS_SOURCE + '\n\n'
    'This candidate safety message is in English. Multilingual medical or agricultural support has not been qualified.'
)
_CHEMICAL = re.compile(r'poison|pesticid|insecticid|herbicid|fertili[sz]|weed\s*killer|chemical|spray|urea', re.I)
_EXPOSURE = re.compile(r'\b(?:swallow|ingest|drank|drink|ate\b|eaten|lick|inhal|breath|splash|expos|on (?:my |the )?(?:skin|eyes?)|dizz|vomit|unconscious|seizure|collapsed?)', re.I)

def reply(question):
    text = str(question)
    if _CHEMICAL.search(text) and _EXPOSURE.search(text):
        return EMERGENCY
    return HOLD
