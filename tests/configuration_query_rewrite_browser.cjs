const {chromium}=require(process.env.PLAYWRIGHT_MODULE||'playwright'),assert=require('node:assert/strict');
(async()=>{const b=await chromium.launch({executablePath:'/usr/bin/google-chrome',args:['--no-sandbox']});
const p=await b.newPage({viewport:{width:1280,height:900}});
await p.addInitScript(()=>localStorage.setItem('cc_cfg_tour_v1','1'));
await p.goto(process.env.CHATIFY_TEST_URL+'/settings.html#sec-model');
await p.waitForFunction(()=>!!window.CCSettingsSimple?.state()?.names);
assert.ok(await p.locator('#rewrite').isVisible(),'query rewrite toggle is offered');
const before=await p.locator('#rewrite').isChecked();
await p.locator('#rewrite').click();
assert.match(await p.locator('#answerDirty').innerText(),/Unsaved answer changes/,'toggling flags unsaved changes');
await p.locator('#apply').click();
await p.waitForFunction(()=>/Applied|saved/i.test(document.querySelector('#msg')?.textContent||''),{timeout:10000});
const saved=await p.evaluate(async()=>((await (await fetch('/api/settings')).json()).settings).query_rewrite);
assert.equal(saved,!before,'server stored the toggled value');
await p.reload();await p.waitForFunction(()=>!!window.CCSettingsSimple?.state()?.names);
assert.equal(await p.locator('#rewrite').isChecked(),!before,'toggle persists across reload');
await p.locator('#rewrite').click();
await p.locator('#apply').click();
await p.waitForFunction(()=>/Applied|saved/i.test(document.querySelector('#msg')?.textContent||''),{timeout:10000});
await b.close();console.log('PASS query rewrite: toggle flags unsaved changes, Apply stores it and it persists across reload')})().catch(e=>{console.error(e);process.exit(1)});
