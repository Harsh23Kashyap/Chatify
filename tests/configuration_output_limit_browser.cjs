const {chromium}=require(process.env.PLAYWRIGHT_MODULE||'playwright'),assert=require('node:assert/strict');
(async()=>{const b=await chromium.launch({executablePath:'/usr/bin/google-chrome',args:['--no-sandbox']});
const p=await b.newPage({viewport:{width:1280,height:900}});
await p.addInitScript(()=>localStorage.setItem('cc_cfg_tour_v1','1'));
await p.goto(process.env.CHATIFY_TEST_URL+'/settings.html#sec-model');
await p.waitForFunction(()=>!!window.CCSettingsSimple?.state()?.names);
assert.ok(await p.locator('#outputLimit').isVisible(),'answer-length limit stays editable');
const before=await p.locator('#outputLimit').inputValue();
const target=before==='4096'?'2048':'4096';
await p.locator('#outputLimit').evaluate((el,v)=>{el.value=v;el.dispatchEvent(new Event('input',{bubbles:true}));el.dispatchEvent(new Event('change',{bubbles:true}))},target);
assert.match(await p.locator('#answerDirty').innerText(),/Unsaved answer changes/,'dirty hint appears before saving');
await p.locator('#apply').click();
await p.waitForFunction(()=>/Applied|saved/i.test(document.querySelector('#msg')?.textContent||''),{timeout:10000});
const saved=await p.evaluate(async()=>((await (await fetch('/api/settings')).json()).settings).max_output_tokens);
assert.equal(String(saved),target,'server stored the new limit');
await p.reload();await p.waitForFunction(()=>!!window.CCSettingsSimple?.state()?.names);
assert.equal(await p.locator('#outputLimit').inputValue(),target,'limit persists across reload');
await p.locator('#outputLimit').evaluate((el,v)=>{el.value=v;el.dispatchEvent(new Event('input',{bubbles:true}));el.dispatchEvent(new Event('change',{bubbles:true}))},before);
await p.locator('#apply').click();
await p.waitForFunction(()=>/Applied|saved/i.test(document.querySelector('#msg')?.textContent||''),{timeout:10000});
await b.close();console.log('PASS output limit: edit flags unsaved changes, Apply stores it server-side and it persists across reload')})().catch(e=>{console.error(e);process.exit(1)});
