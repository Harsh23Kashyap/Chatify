const {chromium}=require(process.env.PLAYWRIGHT_MODULE||'playwright'),assert=require('node:assert/strict');
(async()=>{const b=await chromium.launch({executablePath:'/usr/bin/google-chrome',args:['--no-sandbox']});
const p=await b.newPage({viewport:{width:1280,height:900},acceptDownloads:true});
await p.addInitScript(()=>localStorage.setItem('cc_cfg_tour_v1','1'));
await p.goto(process.env.CHATIFY_TEST_URL+'/settings.html#sec-model');
await p.waitForFunction(()=>!!window.CCSettingsSimple?.state()?.names);
// A saved key must never leak into the default export
await p.locator('.seg button[data-p=openai]').click();
await p.waitForTimeout(300);
const KEY='sk-test-PLACEHOLDER-1234567890abcdef';
await p.locator('#apikey').fill(KEY);
await p.locator('#keysave').click();
await p.waitForFunction(()=>/Key saved privately/.test(document.querySelector('#msg')?.textContent||''),{timeout:10000});
await p.evaluate(()=>document.querySelector('a[href="#sec-portable"]').click());
await p.waitForSelector('#sec-portable.settings-active-panel');
assert.ok(!(await p.locator('#exportKeys').isChecked()),'keys stay excluded unless explicitly requested');
await p.locator('#exportApp').click();
const dlg=p.locator('dialog[open]');
await dlg.waitFor();
assert.match(await dlg.textContent(),/API keys and credentials/,'the readiness dialog names keys as excluded');
const [download]=await Promise.all([p.waitForEvent('download',{timeout:30000}),dlg.getByRole('button',{name:'Download'}).click()]);
const fs=require('node:fs'),path=await download.path();
const buf=fs.readFileSync(path);
assert.ok(buf.length>500,'the bundle downloaded');
assert.ok(!buf.includes(KEY),'the saved key is nowhere in the default export');
assert.match(await p.locator('#exportStatus').innerText(),/downloaded/i,'the result is announced');
await p.evaluate(()=>document.querySelector('a[href="#sec-model"]').click());
await p.waitForSelector('#sec-model.settings-active-panel');
await p.locator('#keyclear').click();
await p.waitForFunction(()=>/Key removed/.test(document.querySelector('#msg')?.textContent||''),{timeout:10000});
const more=p.locator('#seg .chipmore');if(await more.isVisible())await more.click();
await p.locator('.seg button[data-p=mock]').click();
await b.close();console.log('PASS export: readiness dialog names the exclusions, default bundle downloads without any saved key material')})().catch(e=>{console.error(e);process.exit(1)});
